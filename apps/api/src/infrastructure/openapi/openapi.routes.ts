/**
 * Registro explícito de endpoints del documento OpenAPI (HANDOFF 4.5).
 *
 * Es la única fuente de verdad del documento. El test
 * `test/foundation/openapi-routes.test.ts` compara esta lista con los
 * decoradores `@Controller`/`@Get`/`@Post`/... de los controladores reales,
 * de modo que añadir un endpoint y olvidar documentarlo rompe la suite.
 *
 * Los bodies se toman de `@scienpay/shared`; no se duplican DTOs.
 */

export type HttpMethod = 'get' | 'post' | 'patch' | 'put' | 'delete';

export interface OpenApiRoute {
  method: HttpMethod;
  /** Ruta con parámetros estilo OpenAPI: `/payment-requests/{id}`. */
  path: string;
  tag: string;
  operationId: string;
  summary: string;
  /** Roles autorizados o `PUBLIC` para endpoints sin autenticación. */
  roles: readonly UserRole[] | 'PUBLIC';
  /** Esquema del body JSON, si aplica. */
  body?: z.ZodTypeAny;
  /** Esquema de los placeholders `{param}` de la ruta. */
  params?: z.ZodObject<z.ZodRawShape>;
  /** Esquema de los query params. */
  query?: z.ZodTypeAny;
  successStatus?: number;
  success?: z.ZodTypeAny;
  contentType?: 'application/json' | 'application/pdf';
  /** Errores esperados además de los comunes. */
  errors?: number[];
  /** Seguridad adicional por cookie de refresh. */
  cookieAuth?: boolean;
}

